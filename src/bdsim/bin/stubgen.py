#!/usr/bin/env python3
"""
Generate src/bdsim/_blockfactory_stubs.py

BlockFactoryStubs holds stub signatures for all block factory methods.
BlockDiagram inherits from it so that Pylance / mypy can see ``bd.GAIN(...)``
and the rest without needing a .pyi stub file.

The stubs are typing-only and never called: blocks are bound per instance by
``BDSim.blockdiagram()`` from the block library, and these class attributes
are shadowed at that point.

The output is passed through ``ruff format`` so the committed file is already
in the project's canonical format.

Toolbox blocks (RTB, MVTB) cannot be typed from their own packages, because a
type checker sees a single description of BlockDiagram.  bdsim therefore carries
a generated text snapshot of each toolbox's stubs, with no import or install
dependency on the toolbox.  A snapshot goes stale when the toolbox adds or
changes a block: that is a false error in an editor until it is regenerated, and
never a runtime failure.  Checking a snapshot needs the toolbox installed.

Usage:
    python src/bdsim/bin/stubgen.py            # write bdsim's own stubs
    python src/bdsim/bin/stubgen.py --check    # fail if the committed file is stale
    python src/bdsim/bin/stubgen.py --package roboticstoolbox \
        --class-name RTBStubs --out src/bdsim/_stubs_rtb.py
"""

from __future__ import annotations

import argparse
import difflib
import importlib
import importlib.metadata
import inspect
import re
import subprocess
import sys
from pathlib import Path

import bdsim

OWN_PACKAGE = "bdsim"
OWN_CLASS = "BlockFactoryStubs"
OWN_OUTPUT = Path(__file__).parent.parent / "_blockfactory_stubs.py"

_IMPORTS = """\
from __future__ import annotations

from math import inf
from typing import TYPE_CHECKING, Any, Callable, Literal, TextIO
import numpy as np
from matplotlib.axes import Axes
from numpy.typing import ArrayLike
from spatialmath import SE2, SE3, SO2, SO3, Twist3
from spatialmath.base.types import ArrayLike3

if TYPE_CHECKING:
    from bdsim.components import Clock
    from bdsim.blockdiagram import BlockDiagram
    from roboticstoolbox import mobile  # optional dependency

Vector1D = int | float | tuple[float, ...] | list[float] | np.ndarray
"""

_CLASS = '''\

class {cls}:
    """
    Declares stub signatures for {what}.

    ``BlockDiagram`` inherits from this class so that static type checkers
    (Pylance, mypy) can resolve calls like ``bd.STEP()``, ``bd.SCOPE()``, etc.

    At runtime each block is bound to the diagram instance, shadowing these
    class attributes, so these bodies are never executed.
    """
'''


def _distribution(package: str) -> tuple[str, str]:
    """Return the distribution name and version that provide an import package."""
    try:
        dist = importlib.metadata.packages_distributions()[package][0]
        return dist, importlib.metadata.version(dist)
    except KeyError:  # e.g. an editable install, which is not always mapped
        module = importlib.import_module(package)
        return package, getattr(module, "__version__", "of unknown version")


def _header(package: str, cls: str, command: str) -> str:
    """Return the banner, imports and class statement of a stub module."""
    if package == OWN_PACKAGE:
        banner = (
            "# This file is AUTO-GENERATED by src/bdsim/bin/stubgen.py.\n"
            "# Do not edit by hand – run stubgen.py to regenerate.\n"
        )
        what = "all block factory methods"
    else:
        dist, version = _distribution(package)
        banner = (
            "# This file is AUTO-GENERATED by src/bdsim/bin/stubgen.py.\n"
            "# Do not edit by hand.\n"
            f"# Typing-only snapshot of the block factory methods of {dist} {version}.\n"
            "# Regenerate with that toolbox installed:\n"
            f"#   {command}\n"
        )
        what = f"the block factory methods of {package}"
    return banner + _IMPORTS + _CLASS.format(cls=cls, what=what)


def _find_matching_bracket(text: str, start: int) -> int:
    depth = 0

    for index in range(start, len(text)):
        char = text[index]
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return index

    raise ValueError(f"unmatched '[' in {text!r}")


def _split_top_level_args(text: str) -> list[str]:
    args: list[str] = []
    start = 0
    square_depth = 0
    paren_depth = 0
    brace_depth = 0

    for index, char in enumerate(text):
        if char == "[":
            square_depth += 1
        elif char == "]":
            square_depth -= 1
        elif char == "(":
            paren_depth += 1
        elif char == ")":
            paren_depth -= 1
        elif char == "{":
            brace_depth += 1
        elif char == "}":
            brace_depth -= 1
        elif char == "," and square_depth == paren_depth == brace_depth == 0:
            args.append(text[start:index].strip())
            start = index + 1

    args.append(text[start:].strip())
    return args


def _modernize_typing_syntax(text: str) -> str:
    text = text.replace("NoneType", "None")

    while True:
        optional_index = text.find("Optional[")
        union_index = text.find("Union[")
        candidates = [index for index in (optional_index, union_index) if index >= 0]

        if not candidates:
            return text

        start = min(candidates)
        token = "Optional" if start == optional_index else "Union"
        inner_start = start + len(token)
        inner_end = _find_matching_bracket(text, inner_start)
        inner = _modernize_typing_syntax(text[inner_start + 1 : inner_end])

        if token == "Optional":
            replacement = f"{inner} | None"
        else:
            replacement = " | ".join(
                _modernize_typing_syntax(part) for part in _split_top_level_args(inner)
            )

        text = text[:start] + replacement + text[inner_end + 1 :]


def _param_to_str(p: inspect.Parameter) -> str:
    """Stringify a parameter, defaulting missing annotations to Any."""
    prefix = ""
    if p.kind == inspect.Parameter.VAR_POSITIONAL:
        prefix = "*"
    elif p.kind == inspect.Parameter.VAR_KEYWORD:
        prefix = "**"

    has_annotation = p.annotation is not inspect.Parameter.empty
    has_default = p.default is not inspect.Parameter.empty

    if has_annotation:
        ann = p.annotation
        if isinstance(ann, type):
            ann_str = ann.__name__
        elif isinstance(ann, str):
            ann_str = ann
        else:
            ann_str = str(ann)
        # Fix double-qualified names like "typing.typing.Literal" → "Literal"
        # and "typing.Any" → "Any"
        ann_str = ann_str.replace("typing.typing.", "typing.").replace("typing.", "")
        annotation = _modernize_typing_syntax(ann_str)
    else:
        annotation = "Any"

    if has_default:
        default_str = repr(p.default)
        return f"{prefix}{p.name}: {annotation} = {default_str}"
    else:
        return f"{prefix}{p.name}: {annotation}"


def generate(package: str, cls: str, command: str) -> str:
    """Return the text of a stub module for the blocks of ``package``, formatted."""
    sim = bdsim.BDSim(sysargs=False)  # our own argv is not the simulator's

    selected = {
        name: info
        for name, info in sim.block_library.items()
        if info["module"] == package or info["module"].startswith(package + ".")
    }
    if not selected:
        raise RuntimeError(
            f"no blocks found for package {package!r} (is it installed?)"
        )  # pragma: no cover

    out = [_header(package, cls, command)]
    for block, info in sorted(selected.items()):
        meth = info["class"]
        sig = inspect.signature(meth.__init__)

        # Build parameter list, skipping 'self' from __init__ and ensuring
        # **blockargs is present.
        params = [p for p in sig.parameters.values() if p.name != "self"]
        has_blockargs = any(p.kind == inspect.Parameter.VAR_KEYWORD for p in params)
        if not has_blockargs:
            params.append(inspect.Parameter("blockargs", inspect.Parameter.VAR_KEYWORD))

        # Normalize legacy typing spellings that come back from inspect so the
        # generated stubs use the project's modern ``|`` style annotations.
        # Params without annotations default to Any.
        sig_str = "(" + ", ".join(["self"] + [_param_to_str(p) for p in params]) + ")"
        doc = (meth.__init__.__doc__ or "").rstrip()

        out.append(f"\n    # {info['module']}.{info['classname']}\n")
        out.append(f"    def {block}{sig_str} -> Any:\n")
        if doc:
            # Escape backslashes so LaTeX sequences like \omega don't produce
            # SyntaxWarnings in the generated file (Python 3.12+).
            safe_doc = doc.replace("\\", "\\\\")
            out.append(f'        """{safe_doc}\n        """\n')
        out.append(
            "        raise NotImplementedError(  # pragma: no cover\n"
            '            "stub signature -- the real implementation is injected "\n'
            '            "onto BlockDiagram at import time by the @block decorator"\n'
            "        )\n"
        )

    return _ruff_format("".join(out), package)


def _ruff_format(text: str, package: str) -> str:
    """Format source text with the project's ruff configuration."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--stdin-filename",
            f"src/bdsim/_stubs_{package}.py",
            "-",
        ],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def _default_class_name(package: str) -> str:
    return "".join(w.capitalize() for w in re.split(r"\W|_", package) if w) + "Stubs"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--package",
        default=OWN_PACKAGE,
        help="package whose blocks to stub (default: bdsim's own)",
    )
    parser.add_argument("--class-name", help="name of the generated class")
    parser.add_argument(
        "--out", type=Path, help="file to write (required for --package)"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write: exit 1 with a diff if the file differs from a regeneration",
    )
    args = parser.parse_args(argv)

    own = args.package == OWN_PACKAGE
    out = args.out or (OWN_OUTPUT if own else None)
    if out is None:
        parser.error("--out is required with --package")
    cls = args.class_name or (OWN_CLASS if own else _default_class_name(args.package))

    command = "python src/bdsim/bin/stubgen.py"
    if not own:
        command += f" --package {args.package} --class-name {cls} --out {out}"

    text = generate(args.package, cls, command)

    if args.check:
        current = out.read_text() if out.exists() else ""
        if current == text:
            print(f"{out} is up to date")
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile=f"{out} (committed)",
                tofile=f"{out} (regenerated)",
            )
        )
        print(f"\n{out} is stale; regenerate it with:\n  {command}", file=sys.stderr)
        return 1

    out.write_text(text)
    print(f"writing stubs --> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
