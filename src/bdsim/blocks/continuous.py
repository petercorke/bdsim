class Deriv(SubsystemBlock):
    r"""
    :blockname:`DERIV`

    Continuous-time derivative.

    :inputs: 1
    :outputs: 1
    :states: N

    .. list-table::
        :header-rows: 1

        *   - Port type
            - Port number
            - Types
            - Description
        *   - Input
            - 0
            - float
            - :math:`x`
        *   - Output
            - 0
            - float
            - :math:`y`

    Implements the dynamics of a derivative filter, but to be causal (proper) it
    includes a first-order low-pass filter.  The dynamics is

    .. math:: \frac{s}{\frac{s}{\alpha} + 1}

    The pole is at :math:`s=-\alpha`. A small value of ``alpha`` corresponds to a
    long-time constant in the step reponse.   The parameter ``alpha`` can be used to
    achieve the desired tradeoff between noise reduction and phase lag.

    The derivative calculation is performed using a complementary filter,
    implemented as a subsystem with an integrator and a feedback loop.  The initial
    state of the integrator is given by ``x0``::


            +
        u ───> SUM ───────> GAIN(alpha) ──┬───>  GAIN(k) ───> y
                ▲ ─                       │
                │                         │
                └───  INTEGRATOR(x0) <────┘



    If the initial output of the derivative block is known it can be provided as
    ``y0`` from which ``x0`` is calculated by :math:`x_0 = - \alpha y_0`.

    The final GAIN block is only included if ``gain`` is not 1.0, and can be used to
    scale the output of the derivative block.

    .. warning::
        This derivative block has a direct feedthrough term, and depending on how it is used
        in a system it may introduce an an algebraic loop which will be flagged at
        ``compile`` time. The ``Deriv2`` blockis an alternative implementation without direct
        feedthrough and includes a second-order filter which may be more suitable for some applications.

    .. versionchanged:: 1.2.0
        The pole is now at :math:`s=-\alpha` instead of :math:`s=-1/\alpha`.

    :seealso: :class:`Integrator`
    """

    nin = 1
    nout = 1

    def __init__(
        self,
        alpha: float,
        x0: Vector1D = 0,
        y0: Vector1D | None = None,
        gain: float = 1.0,
        **blockargs: Any,
    ) -> None:
        r"""
        :param alpha: filter pole in units of rad/s
        :type alpha: float
        :param x0: initial states, defaults to 0
        :type x0: array_like, optional
        :param y0: inital outputs
        :type y0: array_like
        :param gain: gain or scaling factor, defaults to 1
        :type gain: float, optional
        :param blockargs: :meth:`common block options <bdsim.Block.__init__>`
        :type blockargs: dict
        """

        bd = blockargs["bd"]
        subsystem = bd.runtime.blockdiagram(name="PID")

        if y0 is not None:
            y0 = np.array(smb.getvector(y0), dtype=float).reshape(-1)
            x0 = -y0 * alpha

        integrator = subsystem.INTEGRATOR(x0=x0)
        inp = subsystem.INPORT(1, name="IN")
        outp = subsystem.OUTPORT(1, name="OUT")
        sum = subsystem.SUM("+-", name="SUM")
        alpha_block = subsystem.GAIN(alpha, name="alpha")
        gain_block = subsystem.GAIN(
            gain, name="K"
        )  # always present, so gain can be set

        subsystem.connect(inp, sum[0])
        subsystem.connect(sum[0], alpha_block)
        subsystem.connect(alpha_block, integrator)
        subsystem.connect(integrator, sum[1])
        subsystem.connect(alpha_block, gain_block)
        subsystem.connect(gain_block, outp)

        super().__init__(subsystem=subsystem, **blockargs)
        self._integrator = integrator
        self._alpha_block = alpha_block
        self.add_param("alpha", forward=(alpha_block, "K"))
        self.add_param("gain", forward=(gain_block, "K"))
        self.add_param("x0", forward=(integrator, "x0"))
        self.add_param("y0", when="setup")

    @property
    def y0(self) -> np.ndarray:
        """
        The initial output, which is the initial state :math:`x_0` scaled by the pole
        :math:`\\alpha`: :math:`y_0 = -x_0/\\alpha`.  Setting it sets the state.
        """
        return -self._integrator.x0 / self._alpha_block.K  # type: ignore[no-any-return]

    @y0.setter
    def y0(self, value: Any) -> None:
        y0 = np.array(smb.getvector(value), dtype=float).reshape(-1)
        self._integrator.set_param("x0", -y0 * self._alpha_block.K)


