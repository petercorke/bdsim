class Deriv2(LTI_SS):
    r"""
    :blockname:`DERIV2`

    Continuous-time derivative with second-order filter.

    :inputs: 1
    :outputs: 1
    :states: N

    .. list-table::
        :header-rows: 1

        *   - Port type
            - Port number
            - Types
            - Description
        *   - Input
            - 0
            - float
            - :math:`x`
        *   - Output
            - 0
            - float
            - :math:`y`

    Implements the dynamics of a derivative filter, but to be causal it includes a
    second-order low-pass filter.  The dynamics are

    .. math:: \frac{Y(s)}{U(s)} = \frac{s}{s^2 + 2\omega_n \zeta s + \omega_n^2}

    It is implemented in state-space form using an ``LTI_SS`` block. The state-space model is in observer canonical form, with the state
    vector being the output of the first and second integrators in the chain.  The
    initial state of the integrators is given by ``x0``.  The initial output of the
    derivative block is given by ``x0[0]``.


    :seealso: :class:`Integrator`
    """

    nin = 1
    nout = 1

    def __init__(
        self,
        wn: float,
        unit: str = "rad/s",
        zeta: float = 1,
        x0: Vector1D = (0, 0),
        gain: float = 1.0,
        **blockargs: Any,
    ) -> None:
        r"""
        :param wn: natural frequency in units of rad/s
        :type wn: float
        :param unit: units of wn, defaults to "rad/s"
        :type unit: str, optional
        :param zeta: damping ratio, defaults to 1
        :type zeta: float, optional
        :param x0: initial states, defaults to (0, 0)
        :type x0: array_like, optional
        :param gain: gain or scaling factor, defaults to 1
        :type gain: float, optional
        :param blockargs: :meth:`common block options <bdsim.Block.__init__>`
        :type blockargs: dict

        Damping factor defaults to critical damping, which results in the fastest response without overshoot.
        A smaller value of ``zeta`` results in a faster response but with overshoot, while a larger value results in a slower response with no overshoot.
        Choose ``zeta=0.707`` (:math:`1/\sqrt{2}`) for optimal rise time and overshoot (4.3%).
        """

        A, B, C = self._realisation(wn, unit, zeta, gain)

        # this model is strictly proper, D is zero and can be ommitted.
        super().__init__(A=A, B=B, C=C, x0=x0, **blockargs)
        self.unit = unit
        self._wn, self._zeta, self._gain = wn, zeta, gain

        # A, B and C are derived from wn, zeta and gain, so they are not parameters
        for name in "ABCD":
            self.remove_param(name)
        self.add_param("wn")
        self.add_param("zeta")
        self.add_param("gain")
        self.add_param("unit", when="never")
        self.add_param("x0", when="setup")

    @staticmethod
    def _realisation(
        wn: float, unit: str, zeta: float, gain: float
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """State-space matrices A, B and C of ``gain * wn^2 s / (s^2 + 2 zeta wn s + wn^2)``."""
        if unit == "Hz":
            wn = 2 * pi * wn
        N = [gain * wn**2, 0]  # wn^2 s
        D = [1, 2 * zeta * wn, wn**2]  # s^2 + 2 zeta wn s + wn^2

        A, B, C, _ = _tf2ss(N, D, form="ocf")
        return A, B, C

    def _rebuild(self, wn: float, zeta: float, gain: float) -> None:
        """Change the dynamics, or raise and leave the block as it was."""
        if wn <= 0:
            raise ValueError("wn must be positive")
        self.A, self.B, self.C = self._realisation(wn, self.unit, zeta, gain)
        self._wn, self._zeta, self._gain = wn, zeta, gain

    @property
    def wn(self) -> float:
        """Natural frequency, in ``unit``."""
        return self._wn

    @wn.setter
    def wn(self, value: float) -> None:
        self._rebuild(value, self._zeta, self._gain)

    @property
    def zeta(self) -> float:
        """Damping ratio."""
        return self._zeta

    @zeta.setter
    def zeta(self, value: float) -> None:
        self._rebuild(self._wn, value, self._gain)

    @property
    def gain(self) -> float:
        """Gain or scaling factor."""
        return self._gain

    @gain.setter
    def gain(self, value: float) -> None:
        self._rebuild(self._wn, self._zeta, value)


