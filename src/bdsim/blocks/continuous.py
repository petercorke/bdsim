def _conform_D(block: Any, value: Any) -> np.ndarray | None:
    """
    The feedthrough matrix ``D`` as an LTI block stores it.

    :param block: the LTI block, which has ``B``, ``C`` and ``_feedthrough``
    :param value: the new ``D``, an array, a list, or None for zero
    :return: an ``(nout, nin)`` array, or ``None`` if it is zero and the block has no
        feedthrough
    :raises ValueError: ``D`` does not conform to ``B`` and ``C``, or it is non-zero
        and the block was created without feedthrough

    A block created with ``D = 0`` has no direct feedthrough, which decides where it
    sits in the execution order: its output is computed before its input is known.
    So ``D`` can change from one non-zero value to another, but not from zero to
    non-zero.
    """
    nout, nin = block.C.shape[0], block.B.shape[1]
    if value is None:
        D = np.zeros((nout, nin))
    else:
        D = np.asarray(value, dtype=float)
        if D.ndim < 2 and D.size == nin * nout:  # a number, or a flat list of numbers
            D = D.reshape((nout, nin))
        if D.shape != (nout, nin):
            raise ValueError(
                f"D must be {nout}x{nin} to conform to B and C, not {D.shape}"
            )
    if np.any(D != 0):
        if not block._feedthrough:
            raise ValueError(
                "D cannot be non-zero: the block was created with D = 0, so it has no "
                "direct feedthrough, which fixes its place in the execution order"
            )
        return D
    return D if block._feedthrough else None


class LTI_SS(ContinuousBlock):
    r"""
    :blockname:`LTI_SS`

    Continuous-time state-space LTI dynamics

    :inputs: 1
    :outputs: 1
    :states: N

    .. list-table::
        :header-rows: 1

        *   - Port type
            - Port number
            - Types
            - Description
        *   - Input
            - 0
            - float, ndarray
            - :math:`u`
        *   - Output
            - 0
            - float, ndarray
            - :math:`y`

    Implements the dynamics of a continuous-time multi-input multi-output (MIMO) linear
    time invariant (LTI) system described in statespace form.  The dynamics are given by

    .. math::

        \begin{aligned}
        \dot{x} &= A x + B u \\
        y &= C x
        \end{aligned}

    A direct passthrough component, typically :math:`D`, is not allowed in order
    to avoid algebraic loops.

    Examples::

        lti = bd.LTI_SS(A=-2, B=1, C=-1)

    is the system :math:`\dot{x}=-2x+u, y=-x`.
    """

    nin = 1
    nout = 1

    def __init__(
        self,
        A: np.ndarray,
        B: np.ndarray,
        C: np.ndarray,
        D: np.ndarray | None = None,
        x0: np.ndarray | None = None,
        **blockargs: Any,
    ) -> None:
        r"""
        :param N: numerator coefficients, defaults to 1
        :type N: array_like, optional
        :param A: system matrix, defaults to [1,1]
        :type A: array_like, optional
        :param B: input matrix, defaults to [1]
        :type B: array_like, optional
        :param C: output matrix, defaults to [1]
        :type C: array_like, optional
        :param D: feedthrough matrix, defaults to None
        :type D: array_like, optional
        :param x0: initial states, defaults to None
        :type x0: array_like, optional
        :param blockargs: :meth:`common block options <bdsim.Block.__init__>`
        :type blockargs: dict
        """
        # print('in SS constructor')
        if A.shape[0] != A.shape[1]:
            raise ValueError("A must be square")
        n = A.shape[0]
        if len(B.shape) == 1:
            # 1D array, assume it's a column vector and reshape to (n,1)
            nin = 1
            B = B.reshape((n, 1))
        else:
            nin = B.shape[1]
        if B.shape[0] != n:
            raise ValueError("B must have same number of rows as A")

        if len(C.shape) == 1:
            # 1D array, assume it's a row vector and reshape to (1,n)
            nout = 1
            if C.shape[0] != n:
                raise ValueError("C must have same number of columns as A")
            C = C.reshape((1, n))
        else:
            nout = C.shape[0]
            if C.shape[1] != n:
                raise ValueError("C must have same number of columns as A")

        if D is None:
            D = np.zeros((nout, n))
        elif len(D.shape) == 1:
            if len(D) != nin * nout:
                raise ValueError("D must conform to B and C dimensions")
            D = D.reshape((nout, nin))
        else:
            if D.shape != (nout, nin):
                raise ValueError("D must conform to B and C dimensions")

        self.A = A
        self.B = B
        self.C = C

        if np.any(D != 0):
            # flag we have feedthrough, which may create an algebraic loop
            self._D: np.ndarray | None = D
            feedthrough = True
        else:
            self._D = None
            feedthrough = False

        super().__init__(
            nstates=n, nin=nin, nout=nout, x0=x0, feedthrough=feedthrough, **blockargs
        )
        self.add_param("A")
        self.add_param("B")
        self.add_param("C")
        self.add_param("D")
        self.add_param("x0", when="setup")

    @property
    def D(self) -> np.ndarray | None:
        """The feedthrough matrix, ``None`` if it is zero."""
        return self._D

    @D.setter
    def D(self, value: Any) -> None:
        self._D = _conform_D(self, value)

    def output(self, t: float, u: list[Any], x: np.ndarray) -> list[Any]:
        y = self.C @ x
        if self._D is not None:
            y = y + self._D @ np.array(u)
        if y.size == 1:
            return [y.item()]
        return [y]

    def deriv(self, t: float, u: list[Any], x: np.ndarray) -> np.ndarray:
        # Reshape u and x to (N,1), i.e. column vectors, so
        # no problems with broadcasting between A@x and B@u
        x = x.reshape(-1, 1)
        u_arr = np.array(u).reshape(-1, 1)
        xd = self.A @ x + self.B @ u_arr
        return xd.flatten()


